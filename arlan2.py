import pygame
import random
import sys

pygame.init()

# Размер игрового окна
ШИРИНА_ОКНА = 1000
ВЫСОТА_ОКНА = 600

ОКНО = pygame.display.set_mode((ШИРИНА_ОКНА, ВЫСОТА_ОКНА))
pygame.display.set_caption("Пинг-понг для двух игроков")

# Цвета
ЦВЕТ_ФОНА = (25, 25, 45)
ЦВЕТ_ИГРОКОВ = (255, 255, 255)
ЦВЕТ_МЯЧА = (255, 220, 0)
ЦВЕТ_ЛИНИИ = (100, 100, 130)

# Настройка частоты кадров
ЧАСТОТА_КАДРОВ = 60
ЧАСЫ = pygame.time.Clock()

# Размеры игроков
ШИРИНА_ИГРОКА = 20
ВЫСОТА_ИГРОКА = 120

СКОРОСТЬ_ИГРОКА = 7

# Создание первого игрока
первый_игрок = pygame.Rect(
    50,
    ВЫСОТА_ОКНА // 2 - ВЫСОТА_ИГРОКА // 2,
    ШИРИНА_ИГРОКА,
    ВЫСОТА_ИГРОКА
)

# Создание второго игрока
второй_игрок = pygame.Rect(
    ШИРИНА_ОКНА - 70,
    ВЫСОТА_ОКНА // 2 - ВЫСОТА_ИГРОКА // 2,
    ШИРИНА_ИГРОКА,
    ВЫСОТА_ИГРОКА
)

# Размер мяча
РАЗМЕР_МЯЧА = 20

# Создание мяча
мяч = pygame.Rect(
    ШИРИНА_ОКНА // 2 - РАЗМЕР_МЯЧА // 2,
    ВЫСОТА_ОКНА // 2 - РАЗМЕР_МЯЧА // 2,
    РАЗМЕР_МЯЧА,
    РАЗМЕР_МЯЧА
)

# Скорость мяча
скорость_мяча_по_горизонтали = 6
скорость_мяча_по_вертикали = 5

# Счёт игроков
счёт_первого_игрока = 0
счёт_второго_игрока = 0

# Шрифт для отображения счёта
шрифт_счёта = pygame.font.Font(None, 70)
шрифт_подсказки = pygame.font.Font(None, 30)


def вернуть_мяч_в_центр():
    """
    Возвращает мяч в центр игрового поля
    и задаёт ему случайное направление
    движения.
    """
    global скорость_мяча_по_горизонтали
    global скорость_мяча_по_вертикали

    мяч.center = (
        ШИРИНА_ОКНА // 2,
        ВЫСОТА_ОКНА // 2
    )

    скорость_мяча_по_горизонтали = random.choice([-6, 6])
    скорость_мяча_по_вертикали = random.choice([-5, -4, 4, 5])


def нарисовать_фон():
    """
    Рисует фон игрового поля.
    """
    ОКНО.fill(ЦВЕТ_ФОНА)

    # Центральная линия игрового поля
    for положение_по_вертикали in range(
        0,
        ВЫСОТА_ОКНА,
        30
    ):
        pygame.draw.rect(
            ОКНО,
            ЦВЕТ_ЛИНИИ,
            (
                ШИРИНА_ОКНА // 2 - 2,
                положение_по_вертикали,
                4,
                15
            )
        )


def нарисовать_игроков():
    """
    Рисует двух игроков.
    """
    pygame.draw.rect(
        ОКНО,
        ЦВЕТ_ИГРОКОВ,
        первый_игрок
    )

    pygame.draw.rect(
        ОКНО,
        ЦВЕТ_ИГРОКОВ,
        второй_игрок
    )


def нарисовать_мяч():
    """
    Рисует мяч на игровом поле.
    """
    pygame.draw.ellipse(
        ОКНО,
        ЦВЕТ_МЯЧА,
        мяч
    )


def нарисовать_счёт():
    """
    Показывает счёт двух игроков.
    """
    изображение_счёта_первого_игрока = шрифт_счёта.render(
        str(счёт_первого_игрока),
        True,
        ЦВЕТ_ИГРОКОВ
    )

    изображение_счёта_второго_игрока = шрифт_счёта.render(
        str(счёт_второго_игрока),
        True,
        ЦВЕТ_ИГРОКОВ
    )

    ОКНО.blit(
        изображение_счёта_первого_игрока,
        (
            ШИРИНА_ОКНА // 2 - 100,
            30
        )
    )

    ОКНО.blit(
        изображение_счёта_второго_игрока,
        (
            ШИРИНА_ОКНА // 2 + 70,
            30
        )
    )


def обработать_управление():
    """
    Управляет двумя игроками.

    Первый игрок:
    W - движение вверх.
    S - движение вниз.

    Второй игрок:
    Стрелка вверх - движение вверх.
    Стрелка вниз - движение вниз.
    """
    нажатые_клавиши = pygame.key.get_pressed()

    # Управление первым игроком
    if нажатые_клавиши[pygame.K_w]:
        первый_игрок.y -= СКОРОСТЬ_ИГРОКА

    if нажатые_клавиши[pygame.K_s]:
        первый_игрок.y += СКОРОСТЬ_ИГРОКА

    # Управление вторым игроком
    if нажатые_клавиши[pygame.K_UP]:
        второй_игрок.y -= СКОРОСТЬ_ИГРОКА

    if нажатые_клавиши[pygame.K_DOWN]:
        второй_игрок.y += СКОРОСТЬ_ИГРОКА

    # Запрещаем первому игроку выйти за верхнюю границу
    if первый_игрок.top < 0:
        первый_игрок.top = 0

    # Запрещаем первому игроку выйти за нижнюю границу
    if первый_игрок.bottom > ВЫСОТА_ОКНА:
        первый_игрок.bottom = ВЫСОТА_ОКНА

    # Запрещаем второму игроку выйти за верхнюю границу
    if второй_игрок.top < 0:
        второй_игрок.top = 0

    # Запрещаем второму игроку выйти за нижнюю границу
    if второй_игрок.bottom > ВЫСОТА_ОКНА:
        второй_игрок.bottom = ВЫСОТА_ОКНА


def обработать_движение_мяча():
    """
    Перемещает мяч по игровому полю.
    """
    global скорость_мяча_по_горизонтали
    global скорость_мяча_по_вертикали
    global счёт_первого_игрока
    global счёт_второго_игрока

    # Двигаем мяч
    мяч.x += скорость_мяча_по_горизонтали
    мяч.y += скорость_мяча_по_вертикали

    # Проверка столкновения мяча с верхней границей
    if мяч.top <= 0:
        мяч.top = 0
        скорость_мяча_по_вертикали *= -1

    # Проверка столкновения мяча с нижней границей
    if мяч.bottom >= ВЫСОТА_ОКНА:
        мяч.bottom = ВЫСОТА_ОКНА
        скорость_мяча_по_вертикали *= -1

    # Проверка столкновения мяча с первым игроком
    if мяч.colliderect(первый_игрок):
        if скорость_мяча_по_горизонтали < 0:
            мяч.left = первый_игрок.right
            скорость_мяча_по_горизонтали *= -1

            # Изменяем направление мяча в зависимости
            # от места столкновения с игроком
            расстояние_от_центра = (
                мяч.centery - первый_игрок.centery
            )

            скорость_мяча_по_вертикали = расстояние_от_центра // 10

            if скорость_мяча_по_вертикали == 0:
                скорость_мяча_по_вертикали = 1

    # Проверка столкновения мяча со вторым игроком
    if мяч.colliderect(второй_игрок):
        if скорость_мяча_по_горизонтали > 0:
            мяч.right = второй_игрок.left
            скорость_мяча_по_горизонтали *= -1

            расстояние_от_центра = (
                мяч.centery - второй_игрок.centery
            )

            скорость_мяча_по_вертикали = расстояние_от_центра // 10

            if скорость_мяча_по_вертикали == 0:
                скорость_мяча_по_вертикали = 1

    # Если мяч ушёл за левую границу,
    # очко получает второй игрок
    if мяч.right < 0:
        счёт_второго_игрока += 1
        вернуть_мяч_в_центр()

    # Если мяч ушёл за правую границу,
    # очко получает первый игрок
    if мяч.left > ШИРИНА_ОКНА:
        счёт_первого_игрока += 1
        вернуть_мяч_в_центр()


def нарисовать_подсказки():
    """
    Показывает управление игроками.
    """
    текст_управления = (
        "Игрок 1: W / S   Игрок 2: стрелки вверх / вниз"
    )

    изображение_управления = шрифт_подсказки.render(
        текст_управления,
        True,
        ЦВЕТ_ИГРОКОВ
    )

    ОКНО.blit(
        изображение_управления,
        (
            ШИРИНА_ОКНА // 2 - изображение_управления.get_width() // 2,
            ВЫСОТА_ОКНА - 40
        )
    )


# Главный игровой цикл
игра_запущена = True

while игра_запущена:
    # Обработка событий
    for событие in pygame.event.get():
        # Закрытие окна
        if событие.type == pygame.QUIT:
            игра_запущена = False

        # Выход из игры по клавише Escape
        if событие.type == pygame.KEYDOWN:
            if событие.key == pygame.K_ESCAPE:
                игра_запущена = False

    # Управление игроками
    обработать_управление()

    # Движение мяча и проверка столкновений
    обработать_движение_мяча()

    # Рисуем фон
    нарисовать_фон()

    # Рисуем игроков
    нарисовать_игроков()

    # Рисуем мяч
    нарисовать_мяч()

    # Показываем счёт
    нарисовать_счёт()

    # Показываем управление
    нарисовать_подсказки()

    # Обновляем экран
    pygame.display.flip()

    # Ограничиваем частоту кадров
    ЧАСЫ.tick(ЧАСТОТА_КАДРОВ)

# Завершаем работу pygame
pygame.quit()
sys.exit()